    sort_order          integer      NOT NULL DEFAULT 0,
    status              varchar(16)  NOT NULL DEFAULT 'active',
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_dance_style_style_code UNIQUE (style_code),
    CONSTRAINT fk_dance_style_parent_id
        FOREIGN KEY (parent_id) REFERENCES dance_style(id),
    CONSTRAINT chk_dance_style_style_level CHECK (style_level IN (1, 2))
);

-- =========================================================
-- 表 08: media_asset
-- 关系 08:
--   media_asset.uploader_user_id -> app_user.id
-- 说明：统一存储图片/视频/文档元数据，业务附件关系由 media_attachment 承载
-- =========================================================
CREATE TABLE media_asset (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_type          varchar(16)  NOT NULL,
    biz_type            varchar(32)  NOT NULL,
    storage_provider    varchar(32)  NOT NULL DEFAULT 'oss',
    bucket_name         varchar(128) NOT NULL,
    object_key          varchar(255) NOT NULL,
    origin_file_name    varchar(255) NOT NULL,
    mime_type           varchar(128) NOT NULL,
    file_size           bigint       NOT NULL,
    image_width         integer,
    image_height        integer,
    duration_seconds    numeric(10, 2),
    sha256              varchar(64),
    uploader_user_id    bigint,
    audit_status        varchar(16)  NOT NULL DEFAULT 'pending',
    is_public           boolean      NOT NULL DEFAULT false,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_media_asset_bucket_name_object_key UNIQUE (bucket_name, object_key),
    CONSTRAINT fk_media_asset_uploader_user_id
        FOREIGN KEY (uploader_user_id) REFERENCES app_user(id) ON DELETE SET NULL,
    CONSTRAINT chk_media_asset_asset_type CHECK (asset_type IN ('image', 'video', 'document', 'audio'))
);

