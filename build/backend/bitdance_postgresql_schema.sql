-- BitDance PostgreSQL Schema
-- 目标：覆盖架构文档 3.1 关键实体，并结合第 4 章业务模块修正建模
-- 执行前提：建议在空数据库或独立 schema 中执行
--
-- 建模调整说明：
-- 1. `app_user` 与 `coach` 采用 1:1 扩展，而不是为教练单独再建一套账号表。
-- 2. `favorite`、`review`、`notification`、`report_ticket`、`media_attachment` 采用统一多态目标模型，
--    以避免按舞室/课程/教练/Workshop 各拆一张结构相同的表。
-- 3. `course` 与 `course_schedule` 必须拆分：前者是课程主档，后者是可展示/预约的排期实例。
-- 4. `workshop` 与 `workshop_session` 必须拆分：一个活动可有多个场次，订单和签到都应落在场次级别。
-- 5. `content_post` 与 `growth_work` 保持分表：前者是社区内容，后者是个人成长作品，审核和可见性规则不同。
-- 6. 为补齐第 4 章业务所需，额外增加了 `user_dance_preference`、`catalog_correction_ticket`、
--    `coach_certification_application`、`review_reply`、`group_class_intent`、`badge_definition`、
--    `settlement_rule`、`withdraw_request`、`content_share_log` 等表。
--    结合简易实现补充，增加 `payment_record`、`refund_record`、`idempotency_token`、
--    `data_import_batch`、`user_block_relation`、`behavior_event_log`，用于支付回调、
--    写接口幂等、种子数据导入、拉黑关系和 MVP 指标埋点。
-- 7. 视图用于公共聚合读模型，索引统一采用 `idx_表名_字段名` 前缀规范，函数统一采用 `fn_` 前缀。
-- 8. PostgreSQL 下优先使用 `jsonb`、数组和复合索引承载低频配置型字段，避免为稀疏字段过度拆表。

BEGIN;

CREATE SCHEMA IF NOT EXISTS bitdance;
SET search_path TO bitdance, public;

-- =========================================================
-- 表 01: sys_role
-- 关系 01: 系统角色主数据，供 user_role_binding 引用
-- =========================================================
CREATE TABLE sys_role (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code           varchar(50)  NOT NULL,
    role_name           varchar(100) NOT NULL,
    role_scope          varchar(32)  NOT NULL,
    description         text,
    is_system           boolean      NOT NULL DEFAULT true,
    status              varchar(16)  NOT NULL DEFAULT 'active',
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_sys_role_role_code UNIQUE (role_code),
    CONSTRAINT chk_sys_role_role_scope CHECK (role_scope IN ('app', 'merchant', 'platform', 'all'))
);

-- =========================================================
-- 表 02: sys_permission
-- 关系 02: 权限主数据，供 sys_role_permission 引用
-- =========================================================
CREATE TABLE sys_permission (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_code     varchar(100) NOT NULL,
    permission_name     varchar(100) NOT NULL,
    resource_code       varchar(64)  NOT NULL,
    action_code         varchar(64)  NOT NULL,
    description         text,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_sys_permission_permission_code UNIQUE (permission_code)
);

-- =========================================================
-- 表 03: sys_role_permission
-- 关系 03:
--   sys_role_permission.role_id -> sys_role.id
--   sys_role_permission.permission_id -> sys_permission.id
-- =========================================================
CREATE TABLE sys_role_permission (
    role_id             bigint       NOT NULL,
    permission_id       bigint       NOT NULL,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_sys_role_permission PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_sys_role_permission_role_id
        FOREIGN KEY (role_id) REFERENCES sys_role(id) ON DELETE CASCADE,
    CONSTRAINT fk_sys_role_permission_permission_id
        FOREIGN KEY (permission_id) REFERENCES sys_permission(id) ON DELETE CASCADE
);

-- =========================================================
-- 表 04: app_user
-- 关系 04: 平台统一账号主表，被 profile / role / coach / 订单 / 内容等多表引用
-- =========================================================
CREATE TABLE app_user (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone               varchar(20),
    password_hash       varchar(255),
    wechat_openid       varchar(128),
    wechat_unionid      varchar(128),
    registration_channel varchar(32) NOT NULL DEFAULT 'wechat_mp',
    account_status      varchar(16)  NOT NULL DEFAULT 'active',
    nickname_snapshot   varchar(100),
    last_login_at       timestamptz,
    registered_at       timestamptz  NOT NULL DEFAULT now(),
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_app_user_phone UNIQUE (phone),
    CONSTRAINT uk_app_user_wechat_openid UNIQUE (wechat_openid),
    CONSTRAINT uk_app_user_wechat_unionid UNIQUE (wechat_unionid),
    CONSTRAINT chk_app_user_account_status CHECK (account_status IN ('active', 'frozen', 'disabled'))
);

-- =========================================================
-- 表 05: city
-- 关系 05: 城市字典，供 studio / profile / workshop / practice_post / content_post 引用
-- =========================================================
CREATE TABLE city (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_code           varchar(32)  NOT NULL,
    city_name           varchar(100) NOT NULL,
    province_name       varchar(100) NOT NULL,
    latitude            numeric(10, 6),
    longitude           numeric(10, 6),
    status              varchar(16)  NOT NULL DEFAULT 'active',
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_city_city_code UNIQUE (city_code)
);

-- =========================================================
-- 表 06: business_district
-- 关系 06:
--   business_district.city_id -> city.id
-- =========================================================
CREATE TABLE business_district (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id             bigint       NOT NULL,
    district_name       varchar(100) NOT NULL,
    district_code       varchar(64),
    center_latitude     numeric(10, 6),
    center_longitude    numeric(10, 6),
    radius_km           numeric(6, 2),
    status              varchar(16)  NOT NULL DEFAULT 'active',
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_business_district_city_id_district_name UNIQUE (city_id, district_name),
    CONSTRAINT uk_business_district_district_code UNIQUE (district_code),
    CONSTRAINT fk_business_district_city_id
        FOREIGN KEY (city_id) REFERENCES city(id)
);

-- =========================================================
-- 表 07: dance_style
-- 关系 07:
--   dance_style.parent_id -> dance_style.id
-- =========================================================
CREATE TABLE dance_style (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    style_code          varchar(32)  NOT NULL,
    style_name          varchar(100) NOT NULL,
    parent_id           bigint,
