-- =========================================================
-- 视图 01: vw_review_target_summary
-- 说明：统一产出评价数、验证评价数、平均分、加权平均分
-- =========================================================
CREATE OR REPLACE VIEW vw_review_target_summary AS
SELECT
    r.target_type,
    r.target_id,
    COUNT(*) FILTER (WHERE r.review_status = 'published') AS review_count,
    COUNT(*) FILTER (WHERE r.review_status = 'published' AND r.is_verified) AS verified_review_count,
    ROUND(AVG(r.overall_score) FILTER (WHERE r.review_status = 'published'), 2) AS avg_overall_score,
    ROUND(
        (SUM(r.overall_score * r.weight_factor) FILTER (WHERE r.review_status = 'published'))
        / NULLIF(SUM(r.weight_factor) FILTER (WHERE r.review_status = 'published'), 0),
        2
    ) AS avg_weighted_score
FROM review r
GROUP BY r.target_type, r.target_id;

-- =========================================================
-- 视图 02: vw_growth_user_stats
-- 说明：面向 M5 的成长统计读模型
-- =========================================================
CREATE OR REPLACE VIEW vw_growth_user_stats AS
SELECT
    gc.user_id,
    COUNT(*) AS total_checkins,
    COUNT(DISTINCT gc.checkin_at::date) AS total_checkin_days,
    COALESCE(SUM(gc.duration_minutes), 0) AS total_duration_minutes,
    COUNT(DISTINCT gc.dance_style_id) FILTER (WHERE gc.dance_style_id IS NOT NULL) AS distinct_dance_style_count,
    COUNT(DISTINCT gc.course_schedule_id) FILTER (WHERE gc.course_schedule_id IS NOT NULL) AS related_course_count,
    MIN(gc.checkin_at) AS first_checkin_at,
    MAX(gc.checkin_at) AS last_checkin_at
FROM growth_checkin gc
GROUP BY gc.user_id;

-- =========================================================
-- 视图 03: vw_studio_public_snapshot
-- 说明：面向 M1 的舞室公共聚合视图
-- =========================================================
CREATE OR REPLACE VIEW vw_studio_public_snapshot AS
SELECT
    s.id AS studio_id,
    s.studio_code,
    s.studio_name,
    s.brand_name,
    s.city_id,
    c.city_name,
    s.business_district_id,
    bd.district_name,
    s.address,
    s.longitude,
    s.latitude,
    s.geo_hash,
    s.claim_status,
    s.status,
    COALESCE(cs.course_count, 0) AS course_count,
    COALESCE(cs.published_course_count, 0) AS published_course_count,
    COALESCE(rv.review_count, 0) AS review_count,
    COALESCE(rv.avg_weighted_score, 0.00) AS avg_rating,
    COALESCE(ds.main_styles, '') AS main_styles
FROM studio s
LEFT JOIN city c
    ON c.id = s.city_id
LEFT JOIN business_district bd
    ON bd.id = s.business_district_id
LEFT JOIN (
    SELECT
        c1.studio_id,
        COUNT(*) AS course_count,
        COUNT(*) FILTER (WHERE c1.status = 'published') AS published_course_count
    FROM course c1
    GROUP BY c1.studio_id
) cs
    ON cs.studio_id = s.id
LEFT JOIN vw_review_target_summary rv
    ON rv.target_type = 'studio' AND rv.target_id = s.id
LEFT JOIN (
    SELECT
        sds.studio_id,
        string_agg(ds1.style_name, ', ' ORDER BY ds1.sort_order, ds1.id) AS main_styles
    FROM studio_dance_style sds
    JOIN dance_style ds1
        ON ds1.id = sds.dance_style_id
    GROUP BY sds.studio_id
) ds
    ON ds.studio_id = s.id;

-- =========================================================
-- 视图 04: vw_workshop_public_snapshot
-- 说明：面向 M6 的活动公共聚合视图
-- =========================================================
CREATE OR REPLACE VIEW vw_workshop_public_snapshot AS
SELECT
    w.id AS workshop_id,
    w.workshop_name,
    w.city_id,
    w.studio_id,
    w.coach_id,
    w.dance_style_id,
    w.price_amount,
    w.geo_hash,
    w.signup_deadline,
    w.audit_status,
    w.publish_status,
    ns.id AS next_session_id,
    ns.start_at AS next_session_start_at,
    ns.end_at AS next_session_end_at,
    COALESCE(ss.total_capacity, 0) AS total_capacity,
    COALESCE(os.total_paid_count, 0) AS total_paid_count,
    COALESCE(os.total_completed_count, 0) AS total_completed_count,
    GREATEST(COALESCE(ss.total_capacity, 0) - COALESCE(os.total_paid_count, 0), 0) AS total_remaining_seats
FROM workshop w
LEFT JOIN LATERAL (
    SELECT
        ws.id,
        ws.start_at,
        ws.end_at
    FROM workshop_session ws
    WHERE ws.workshop_id = w.id
      AND ws.session_status IN ('scheduled', 'open')
    ORDER BY ws.start_at
    LIMIT 1
) ns ON true
LEFT JOIN (
    SELECT
        ws2.workshop_id,
        SUM(ws2.capacity) AS total_capacity
    FROM workshop_session ws2
    GROUP BY ws2.workshop_id
) ss
    ON ss.workshop_id = w.id
LEFT JOIN (
    SELECT
        wo.workshop_id,
        COUNT(*) FILTER (WHERE wo.order_status IN ('paid', 'completed')) AS total_paid_count,
        COUNT(*) FILTER (WHERE wo.order_status = 'completed') AS total_completed_count
    FROM workshop_order wo
    GROUP BY wo.workshop_id
) os
    ON os.workshop_id = w.id;

