    CONSTRAINT chk_studio_longitude CHECK (longitude IS NULL OR (longitude >= -180 AND longitude <= 180)),
    CONSTRAINT chk_studio_latitude CHECK (latitude IS NULL OR (latitude >= -90 AND latitude <= 90))
);

