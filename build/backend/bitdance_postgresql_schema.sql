CREATE OR REPLACE FUNCTION fn_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION fn_haversine_km(
    p_lat1 double precision,
    p_lon1 double precision,
    p_lat2 double precision,
    p_lon2 double precision
)
RETURNS numeric
LANGUAGE sql
IMMUTABLE
AS $$
    SELECT ROUND(
        (
            6371 * acos(
                LEAST(
                    1.0,
                    GREATEST(
                        -1.0,
                        cos(radians(p_lat1)) * cos(radians(p_lat2)) * cos(radians(p_lon2) - radians(p_lon1))
                        + sin(radians(p_lat1)) * sin(radians(p_lat2))
                    )
                )
            )
        )::numeric,
        3
    );
$$;

CREATE OR REPLACE FUNCTION fn_normalize_buddy_relation_pair()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_low  bigint;
    v_high bigint;
BEGIN
    IF NEW.user_id_low = NEW.user_id_high THEN
        RAISE EXCEPTION 'buddy relation users must be different';
    END IF;

    IF NEW.user_id_low > NEW.user_id_high THEN
        v_low := NEW.user_id_high;
        v_high := NEW.user_id_low;
        NEW.user_id_low := v_low;
        NEW.user_id_high := v_high;
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION fn_close_expired_practice_posts()
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE
    v_affected integer;
BEGIN
    UPDATE practice_post
       SET post_status = 'expired',
           updated_at = now()
     WHERE post_status IN ('draft', 'published', 'matched')
       AND expires_at < now();

    GET DIAGNOSTICS v_affected = ROW_COUNT;
    RETURN v_affected;
END;
$$;

