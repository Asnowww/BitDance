-- M4 practice completion confirmation migration for existing BitDance schemas.

CREATE TABLE IF NOT EXISTS practice_completion_confirm (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    practice_post_id    bigint       NOT NULL,
    user_id             bigint       NOT NULL,
    confirmed_at        timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_practice_completion_confirm_post_user
        UNIQUE (practice_post_id, user_id),
    CONSTRAINT fk_practice_completion_confirm_practice_post_id
        FOREIGN KEY (practice_post_id) REFERENCES practice_post(id) ON DELETE CASCADE,
    CONSTRAINT fk_practice_completion_confirm_user_id
        FOREIGN KEY (user_id) REFERENCES app_user(id)
);

CREATE INDEX IF NOT EXISTS idx_practice_completion_confirm_practice_post_id
    ON practice_completion_confirm (practice_post_id);

CREATE INDEX IF NOT EXISTS idx_practice_completion_confirm_user_id
    ON practice_completion_confirm (user_id);
