-- M4 group-class intent runtime database patch.
-- Apply this to the PostgreSQL database used by application-local.yml when
-- Hibernate reports: missing table [group_class_intent].

SET search_path TO bitdance, public;

CREATE OR REPLACE FUNCTION fn_set_updated_at()
RETURNS trigger AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE IF NOT EXISTS group_class_intent (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_user_id     bigint       NOT NULL,
    studio_id           bigint       NOT NULL,
    dance_style_id      bigint       NOT NULL,
    preferred_time_note text,
    target_people_count integer      NOT NULL DEFAULT 4,
    current_people_count integer     NOT NULL DEFAULT 1,
    intent_status       varchar(16)  NOT NULL DEFAULT 'collecting',
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT fk_group_class_intent_creator_user_id
        FOREIGN KEY (creator_user_id) REFERENCES app_user(id),
    CONSTRAINT fk_group_class_intent_studio_id
        FOREIGN KEY (studio_id) REFERENCES studio(id),
    CONSTRAINT fk_group_class_intent_dance_style_id
        FOREIGN KEY (dance_style_id) REFERENCES dance_style(id),
    CONSTRAINT chk_group_class_intent_people
        CHECK (target_people_count > 0 AND current_people_count > 0),
    CONSTRAINT chk_group_class_intent_status
        CHECK (intent_status IN ('collecting', 'matched', 'closed', 'canceled'))
);

CREATE TABLE IF NOT EXISTS group_class_intent_participant (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intent_id           bigint       NOT NULL,
    user_id             bigint       NOT NULL,
    participant_status  varchar(16)  NOT NULL DEFAULT 'joined',
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_group_class_intent_participant_intent_id_user_id
        UNIQUE (intent_id, user_id),
    CONSTRAINT fk_group_class_intent_participant_intent_id
        FOREIGN KEY (intent_id) REFERENCES group_class_intent(id) ON DELETE CASCADE,
    CONSTRAINT fk_group_class_intent_participant_user_id
        FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT chk_group_class_intent_participant_status
        CHECK (participant_status IN ('joined', 'canceled'))
);

CREATE INDEX IF NOT EXISTS idx_group_class_intent_studio_id_intent_status
    ON group_class_intent (studio_id, intent_status);

CREATE INDEX IF NOT EXISTS idx_group_class_intent_participant_user_id
    ON group_class_intent_participant (user_id);

CREATE INDEX IF NOT EXISTS idx_group_class_intent_participant_intent_id_status
    ON group_class_intent_participant (intent_id, participant_status);

DROP TRIGGER IF EXISTS trg_group_class_intent_updated_at ON group_class_intent;
CREATE TRIGGER trg_group_class_intent_updated_at
BEFORE UPDATE ON group_class_intent
FOR EACH ROW
EXECUTE FUNCTION fn_set_updated_at();

DROP TRIGGER IF EXISTS trg_group_class_intent_participant_updated_at ON group_class_intent_participant;
CREATE TRIGGER trg_group_class_intent_participant_updated_at
BEFORE UPDATE ON group_class_intent_participant
FOR EACH ROW
EXECUTE FUNCTION fn_set_updated_at();
