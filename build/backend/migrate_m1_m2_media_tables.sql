-- M1/M2 media support migration for an existing BitDance schema.
-- This is intentionally narrow: it only adds media metadata, media attachments, and seed-import audit tables.

BEGIN;

SET search_path TO bitdance, public;

-- 兼容已有云库：若基础 schema 没有更新时间触发函数，这里补一个通用函数供三张新表复用。
CREATE OR REPLACE FUNCTION fn_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

-- M2 图文评价和 M1 封面图依赖该表保存图片/视频元数据，不保存二进制文件。
CREATE TABLE IF NOT EXISTS media_asset (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_type          varchar(16)  NOT NULL,
    biz_type            varchar(32)  NOT NULL,
    storage_provider    varchar(32)  NOT NULL DEFAULT 'oss',
    bucket_name         varchar(128) NOT NULL,
    object_key          varchar(255) NOT NULL,
    origin_file_name    varchar(255) NOT NULL,
    mime_type           varchar(128) NOT NULL,
    file_size           bigint       NOT NULL,
    image_width         integer,
    image_height        integer,
    duration_seconds    numeric(10, 2),
    sha256              varchar(64),
    uploader_user_id    bigint,
    audit_status        varchar(16)  NOT NULL DEFAULT 'pending',
    is_public           boolean      NOT NULL DEFAULT false,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_media_asset_bucket_name_object_key UNIQUE (bucket_name, object_key),
    CONSTRAINT fk_media_asset_uploader_user_id
        FOREIGN KEY (uploader_user_id) REFERENCES app_user(id) ON DELETE SET NULL,
    CONSTRAINT chk_media_asset_asset_type CHECK (asset_type IN ('image', 'video', 'document', 'audio'))
);

-- M2 评价媒体采用多态附件关系，后续同一结构可复用到舞室、课程、教练、作品和动态。
CREATE TABLE IF NOT EXISTS media_attachment (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id            bigint       NOT NULL,
    target_type         varchar(32)  NOT NULL,
    target_id           bigint       NOT NULL,
    usage_type          varchar(32)  NOT NULL,
    sort_order          integer      NOT NULL DEFAULT 0,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_media_attachment_asset_id_target_type_target_id_usage_type
        UNIQUE (asset_id, target_type, target_id, usage_type),
    CONSTRAINT fk_media_attachment_asset_id
        FOREIGN KEY (asset_id) REFERENCES media_asset(id) ON DELETE CASCADE
);

-- 种子数据导入留痕表；不是业务路径强依赖，但用于记录本轮 M1/M2 媒体补种结果。
CREATE TABLE IF NOT EXISTS data_import_batch (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no            varchar(64)  NOT NULL,
    import_type         varchar(32)  NOT NULL,
    source_type         varchar(32)  NOT NULL DEFAULT 'platform_import',
    source_file_asset_id bigint,
    created_by_user_id  bigint,
    total_count         integer      NOT NULL DEFAULT 0,
    success_count       integer      NOT NULL DEFAULT 0,
    failure_count       integer      NOT NULL DEFAULT 0,
    import_status       varchar(16)  NOT NULL DEFAULT 'pending',
    error_summary       text,
    finished_at         timestamptz,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_data_import_batch_batch_no UNIQUE (batch_no),
    CONSTRAINT fk_data_import_batch_source_file_asset_id
        FOREIGN KEY (source_file_asset_id) REFERENCES media_asset(id) ON DELETE SET NULL,
    CONSTRAINT fk_data_import_batch_created_by_user_id
        FOREIGN KEY (created_by_user_id) REFERENCES app_user(id) ON DELETE SET NULL,
    CONSTRAINT chk_data_import_batch_import_type CHECK (import_type IN ('studio', 'course', 'coach', 'workshop', 'dictionary', 'other')),
    CONSTRAINT chk_data_import_batch_source_type CHECK (source_type IN ('platform_import', 'merchant_upload', 'admin_upload', 'user_correction')),
    CONSTRAINT chk_data_import_batch_status CHECK (import_status IN ('pending', 'processing', 'succeeded', 'partial_failed', 'failed')),
    CONSTRAINT chk_data_import_batch_counts CHECK (total_count >= 0 AND success_count >= 0 AND failure_count >= 0)
);

CREATE INDEX IF NOT EXISTS idx_media_asset_uploader_user_id
    ON media_asset (uploader_user_id);

CREATE INDEX IF NOT EXISTS idx_media_attachment_target_type_target_id
    ON media_attachment (target_type, target_id);

CREATE INDEX IF NOT EXISTS idx_media_attachment_asset_id
    ON media_attachment (asset_id);

CREATE INDEX IF NOT EXISTS idx_data_import_batch_import_type_status
    ON data_import_batch (import_type, import_status);

DROP TRIGGER IF EXISTS trg_media_asset_updated_at ON media_asset;
CREATE TRIGGER trg_media_asset_updated_at
BEFORE UPDATE ON media_asset
FOR EACH ROW
EXECUTE FUNCTION fn_set_updated_at();

DROP TRIGGER IF EXISTS trg_data_import_batch_updated_at ON data_import_batch;
CREATE TRIGGER trg_data_import_batch_updated_at
BEFORE UPDATE ON data_import_batch
FOR EACH ROW
EXECUTE FUNCTION fn_set_updated_at();

COMMIT;
