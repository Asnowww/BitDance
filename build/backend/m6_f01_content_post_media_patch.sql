CREATE TABLE IF NOT EXISTS bitdance.content_post_media (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_post_id     bigint,
    owner_user_id       bigint       NOT NULL,
    media_type          varchar(16)  NOT NULL,
    original_filename   varchar(255),
    mime_type           varchar(100) NOT NULL,
    file_size           bigint       NOT NULL,
    media_data          bytea        NOT NULL,
    sort_order          integer      NOT NULL DEFAULT 0,
    media_status        varchar(16)  NOT NULL DEFAULT 'draft',
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT fk_content_post_media_content_post_id
        FOREIGN KEY (content_post_id) REFERENCES bitdance.content_post(id) ON DELETE CASCADE,
    CONSTRAINT fk_content_post_media_owner_user_id
        FOREIGN KEY (owner_user_id) REFERENCES bitdance.app_user(id) ON DELETE CASCADE,
    CONSTRAINT chk_content_post_media_type CHECK (media_type IN ('image', 'video')),
    CONSTRAINT chk_content_post_media_status CHECK (media_status IN ('draft', 'active', 'deleted')),
    CONSTRAINT chk_content_post_media_size CHECK (file_size > 0)
);

CREATE INDEX IF NOT EXISTS idx_content_post_media_post_sort
    ON bitdance.content_post_media (content_post_id, sort_order, id);

CREATE INDEX IF NOT EXISTS idx_content_post_media_owner_status
    ON bitdance.content_post_media (owner_user_id, media_status, created_at DESC);
