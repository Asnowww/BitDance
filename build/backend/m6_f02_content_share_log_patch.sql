CREATE TABLE IF NOT EXISTS bitdance.content_share_log (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_post_id     bigint       NOT NULL,
    user_id             bigint       NOT NULL,
    share_channel       varchar(32)  NOT NULL,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT fk_content_share_log_content_post_id
        FOREIGN KEY (content_post_id) REFERENCES bitdance.content_post(id) ON DELETE CASCADE,
    CONSTRAINT fk_content_share_log_user_id
        FOREIGN KEY (user_id) REFERENCES bitdance.app_user(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_content_share_log_content_post_id
    ON bitdance.content_share_log (content_post_id);

CREATE INDEX IF NOT EXISTS idx_content_share_log_user_id
    ON bitdance.content_share_log (user_id);
