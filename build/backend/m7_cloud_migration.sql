CREATE TABLE IF NOT EXISTS bitdance.course_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no varchar(64) NOT NULL UNIQUE,
    course_id bigint NOT NULL REFERENCES bitdance.course(id),
    course_schedule_id bigint NOT NULL REFERENCES bitdance.course_schedule(id),
    studio_id bigint NOT NULL REFERENCES bitdance.studio(id),
    coach_id bigint REFERENCES bitdance.coach(id),
    user_id bigint NOT NULL REFERENCES bitdance.app_user(id),
    amount_payable numeric(10,2) NOT NULL,
    amount_paid numeric(10,2) NOT NULL DEFAULT 0.00,
    order_status varchar(24) NOT NULL DEFAULT 'pending_payment',
    payment_txn_no varchar(128),
    checkin_code varchar(8),
    paid_at timestamptz,
    canceled_at timestamptz,
    refund_requested_at timestamptz,
    refunded_at timestamptz,
    completed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT chk_course_order_status CHECK (
        order_status IN (
            'pending_payment', 'paid', 'refund_requested', 'refunded',
            'refund_rejected', 'checked_in', 'completed', 'canceled'
        )
    ),
    CONSTRAINT chk_course_order_checkin_code CHECK (checkin_code IS NULL OR checkin_code ~ '^[0-9]{8}$')
);

CREATE TABLE IF NOT EXISTS bitdance.course_checkin (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_order_id bigint NOT NULL UNIQUE REFERENCES bitdance.course_order(id),
    course_schedule_id bigint NOT NULL REFERENCES bitdance.course_schedule(id),
    checkin_code varchar(8) NOT NULL,
    checked_in_by_user_id bigint REFERENCES bitdance.app_user(id),
    checked_in_at timestamptz,
    checkin_status varchar(24) NOT NULL DEFAULT 'active',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT chk_course_checkin_status CHECK (checkin_status IN ('active', 'checked_in', 'expired')),
    CONSTRAINT chk_course_checkin_code CHECK (checkin_code ~ '^[0-9]{8}$')
);

CREATE TABLE IF NOT EXISTS bitdance.course_refund_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_order_id bigint NOT NULL REFERENCES bitdance.course_order(id),
    requester_user_id bigint NOT NULL REFERENCES bitdance.app_user(id),
    refund_reason text,
    request_status varchar(24) NOT NULL DEFAULT 'pending',
    reviewed_by_user_id bigint REFERENCES bitdance.app_user(id),
    reviewed_at timestamptz,
    review_remark text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT chk_course_refund_status CHECK (request_status IN ('pending', 'approved', 'rejected'))
);

CREATE INDEX IF NOT EXISTS idx_course_order_user_created ON bitdance.course_order(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_course_order_studio_status_created ON bitdance.course_order(studio_id, order_status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_course_order_schedule_status ON bitdance.course_order(course_schedule_id, order_status);
CREATE INDEX IF NOT EXISTS idx_course_order_checkin_code ON bitdance.course_order(checkin_code);
CREATE INDEX IF NOT EXISTS idx_course_checkin_code ON bitdance.course_checkin(checkin_code);
CREATE INDEX IF NOT EXISTS idx_course_checkin_history ON bitdance.course_checkin(course_schedule_id, checked_in_at DESC);
CREATE INDEX IF NOT EXISTS idx_course_refund_status_created ON bitdance.course_refund_request(request_status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_course_refund_order ON bitdance.course_refund_request(course_order_id);
