-- Keep identity sequences ahead after fixed dictionary IDs and generated correction/import rows.
DO $$
DECLARE
    t text;
    seq_name text;
    id_tables text[] := ARRAY['city', 'business_district', 'catalog_correction_ticket', 'data_import_batch'];
BEGIN
    FOREACH t IN ARRAY id_tables LOOP
        SELECT pg_get_serial_sequence('bitdance.' || t, 'id') INTO seq_name;
        IF seq_name IS NOT NULL THEN
            EXECUTE format(
                'SELECT setval(%L, (SELECT GREATEST(COALESCE(MAX(id), 1), 1) FROM bitdance.%I), true)',
                seq_name,
                t
            );
        END IF;
    END LOOP;
END;
$$;

