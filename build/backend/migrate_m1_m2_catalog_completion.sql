-- M1 课表/试听演示数据滚动到未来一周；只处理 100000 段 mock 排期，避免改动真实运营排期。
WITH ranked_schedule AS (
    SELECT id, row_number() OVER (ORDER BY id) AS rn
    FROM course_schedule
    WHERE id >= 100000 AND id < 200000
)
UPDATE course_schedule cs
SET
    start_at = (
        (current_date + 1 + (((rs.rn::integer - 1) % 6)))::timestamp
        + make_interval(hours => 10 + (((rs.rn::integer - 1) % 4) * 2))
    ) AT TIME ZONE 'Asia/Shanghai',
    end_at = (
        (current_date + 1 + (((rs.rn::integer - 1) % 6)))::timestamp
        + make_interval(hours => 12 + (((rs.rn::integer - 1) % 4) * 2))
    ) AT TIME ZONE 'Asia/Shanghai',
    capacity = COALESCE(cs.capacity, 12),
    booked_count = LEAST(COALESCE(cs.booked_count, 0), GREATEST(COALESCE(cs.capacity, 12) - 1, 0)),
    status = 'scheduled',
    updated_at = now()
FROM ranked_schedule rs
WHERE cs.id = rs.id;

-- 资料纠错演示数据：每家舞室一条交通信息纠错，重复执行不会重复插入。
WITH ranked_studio AS (
    SELECT id, transport_info, row_number() OVER (ORDER BY id) AS rn
    FROM studio
    ORDER BY id
    LIMIT 10
),
ranked_user AS (
    SELECT id, row_number() OVER (ORDER BY id) AS rn
    FROM app_user
    ORDER BY id
    LIMIT 10
),
seed_ticket AS (
    SELECT
        'studio'::varchar(16) AS target_type,
        s.id AS target_id,
        u.id AS reporter_user_id,
        'transport_info'::varchar(64) AS field_name,
        COALESCE(s.transport_info, '') AS old_value,
        ('地铁步行 ' || (5 + s.rn) || ' 分钟，楼下有停车场') AS proposed_value,
        'M1 演示数据：补充舞室交通信息' AS correction_reason,
        CASE WHEN s.rn <= 7 THEN 'approved' ELSE 'pending' END AS ticket_status
    FROM ranked_studio s
    JOIN ranked_user u ON u.rn = s.rn
)
INSERT INTO catalog_correction_ticket (
    target_type, target_id, reporter_user_id, field_name, old_value,
    proposed_value, correction_reason, ticket_status, reviewed_by_user_id,
    reviewed_at, review_remark
)
SELECT
    target_type, target_id, reporter_user_id, field_name, old_value,
    proposed_value, correction_reason, ticket_status,
    CASE WHEN ticket_status = 'approved' THEN reporter_user_id ELSE NULL END,
    CASE WHEN ticket_status = 'approved' THEN now() ELSE NULL END,
    CASE WHEN ticket_status = 'approved' THEN 'M1 演示纠错已采纳' ELSE NULL END
FROM seed_ticket st
WHERE NOT EXISTS (
    SELECT 1
    FROM catalog_correction_ticket c
    WHERE c.target_type = st.target_type
      AND c.target_id = st.target_id
      AND c.reporter_user_id = st.reporter_user_id
      AND c.field_name = st.field_name
      AND c.proposed_value = st.proposed_value
);

-- 已采纳的演示纠错同步回舞室交通信息，驱动 M1 列表筛选 nearMetro/详情交通展示。
UPDATE studio s
SET transport_info = c.proposed_value,
    updated_at = now()
FROM catalog_correction_ticket c
WHERE c.target_type = 'studio'
  AND c.target_id = s.id
  AND c.field_name = 'transport_info'
  AND c.ticket_status = 'approved'
  AND c.correction_reason = 'M1 演示数据：补充舞室交通信息';

