-- 在字典数据补齐后再添加外键，避免旧云库先有 studio 数据时约束创建失败。
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_business_district_city_id'
          AND conrelid = 'bitdance.business_district'::regclass
    ) THEN
        ALTER TABLE business_district
            ADD CONSTRAINT fk_business_district_city_id
            FOREIGN KEY (city_id) REFERENCES city(id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_studio_city_id'
          AND conrelid = 'bitdance.studio'::regclass
    ) THEN
        ALTER TABLE studio
            ADD CONSTRAINT fk_studio_city_id
            FOREIGN KEY (city_id) REFERENCES city(id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_studio_business_district_id'
          AND conrelid = 'bitdance.studio'::regclass
    ) THEN
        ALTER TABLE studio
            ADD CONSTRAINT fk_studio_business_district_id
            FOREIGN KEY (business_district_id) REFERENCES business_district(id);
    END IF;
END;
$$;

