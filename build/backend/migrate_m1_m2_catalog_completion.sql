-- 兼容当前云库：若前一批媒体迁移尚未执行，这里也补充更新时间触发函数。
CREATE OR REPLACE FUNCTION fn_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

-- M1 城市筛选和资料展示依赖城市字典；当前云库缺表时按完整 schema 补齐。
CREATE TABLE IF NOT EXISTS city (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_code           varchar(32)  NOT NULL,
    city_name           varchar(100) NOT NULL,
    province_name       varchar(100) NOT NULL,
    latitude            numeric(10, 6),
    longitude           numeric(10, 6),
    status              varchar(16)  NOT NULL DEFAULT 'active',
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_city_city_code UNIQUE (city_code)
);

-- M1 商圈筛选和舞室交通信息依赖商圈字典；先补北京 10 个演示商圈匹配现有 studio.business_district_id。
CREATE TABLE IF NOT EXISTS business_district (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id             bigint       NOT NULL,
    district_name       varchar(100) NOT NULL,
    district_code       varchar(64),
    center_latitude     numeric(10, 6),
    center_longitude    numeric(10, 6),
    radius_km           numeric(6, 2),
    status              varchar(16)  NOT NULL DEFAULT 'active',
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_business_district_city_id_district_name UNIQUE (city_id, district_name),
    CONSTRAINT uk_business_district_district_code UNIQUE (district_code)
);

-- M1 资料纠错表：用于用户/平台对舞室、课程、教练基础信息发起纠错。
CREATE TABLE IF NOT EXISTS catalog_correction_ticket (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type         varchar(16)  NOT NULL,
    target_id           bigint       NOT NULL,
    reporter_user_id    bigint       NOT NULL,
    field_name          varchar(64)  NOT NULL,
    old_value           text,
    proposed_value      text,
    correction_reason   text,
    ticket_status       varchar(16)  NOT NULL DEFAULT 'pending',
    reviewed_by_user_id bigint,
    reviewed_at         timestamptz,
    review_remark       text,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT fk_catalog_correction_ticket_reporter_user_id
        FOREIGN KEY (reporter_user_id) REFERENCES app_user(id),
    CONSTRAINT fk_catalog_correction_ticket_reviewed_by_user_id
        FOREIGN KEY (reviewed_by_user_id) REFERENCES app_user(id),
    CONSTRAINT chk_catalog_correction_ticket_target_type CHECK (target_type IN ('studio', 'course', 'coach')),
    CONSTRAINT chk_catalog_correction_ticket_status CHECK (ticket_status IN ('pending', 'approved', 'rejected'))
);

