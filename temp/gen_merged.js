const border = { style: BorderStyle.SINGLE, size: 1, color: "AAAAAA" };
const borders = { top: border, bottom: border, left: border, right: border };
const cellMargins = { top: 60, bottom: 60, left: 100, right: 100 };

function cell(text, opts = {}) {
  const runs = Array.isArray(text) ? text : [new TextRun({ text, font: "Microsoft YaHei", size: 21, ...opts.runOpts })];
  return new TableCell({
    borders, margins: cellMargins,
    width: opts.width ? { size: opts.width, type: WidthType.DXA } : undefined,
    shading: opts.shading ? { fill: opts.shading, type: ShadingType.CLEAR } : undefined,
    children: [new Paragraph({ alignment: opts.align || AlignmentType.LEFT, children: runs })],
    columnSpan: opts.colspan,
  });
}
function headerCell(text, width) {
  return cell(text, { width, shading: "2E75B6", runOpts: { bold: true, color: "FFFFFF", size: 21 } });
}

function h1(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_1, spacing: { before: 360, after: 200 },
    children: [new TextRun({ text, font: "Microsoft YaHei", size: 32, bold: true, color: "1F4E79" })] });
}
function h2(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_2, spacing: { before: 280, after: 160 },
    children: [new TextRun({ text, font: "Microsoft YaHei", size: 28, bold: true, color: "2E75B6" })] });
}
function h3(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_3, spacing: { before: 200, after: 120 },
    children: [new TextRun({ text, font: "Microsoft YaHei", size: 24, bold: true, color: "2E75B6" })] });
}
function p(text, opts = {}) {
  return new Paragraph({ spacing: { after: 120, line: 360 }, alignment: opts.align || AlignmentType.LEFT,
    children: [new TextRun({ text, font: "Microsoft YaHei", size: 21, ...opts })] });
}
function pMulti(runs) {
  return new Paragraph({ spacing: { after: 120, line: 360 },
    children: runs.map(r => typeof r === "string" ? new TextRun({ text: r, font: "Microsoft YaHei", size: 21 }) : new TextRun({ font: "Microsoft YaHei", size: 21, ...r })) });
}
function pb(label, value) {
  return new Paragraph({ spacing: { after: 80, line: 360 }, children: [
    new TextRun({ text: label, font: "Microsoft YaHei", size: 21, bold: true }),
    new TextRun({ text: value, font: "Microsoft YaHei", size: 21 }),
  ]});
}
function pLink(text, url) {
  return new Paragraph({ spacing: { after: 80, line: 360 }, children: [
    new ExternalHyperlink({ children: [new TextRun({ text, style: "Hyperlink", font: "Microsoft YaHei", size: 21 })], link: url })
  ]});
}

